pub const HID_LCTRL: u16 = 0xE0;
pub const HID_LSHIFT: u16 = 0xE1;
pub const HID_LALT: u16 = 0xE2;
pub const HID_LGUI: u16 = 0xE3;
pub const HID_RCTRL: u16 = 0xE4;
pub const HID_RSHIFT: u16 = 0xE5;
pub const HID_RALT: u16 = 0xE6;
pub const HID_RGUI: u16 = 0xE7;
pub const HID_ESC: u16 = 0x29;
pub const HID_L: u16 = 0x0F;
pub const HID_PAUSE: u16 = 0x48;
pub const HID_NUMLOCK: u16 = 0x53;

pub fn hid_from_win(scan: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.1 == scan).map(|e| e.0)
}

pub fn win_from_hid(hid: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.0 == hid).map(|e| e.1).filter(|&s| s != NONE)
}

pub fn hid_from_mac(code: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.2 == code).map(|e| e.0)
}

pub fn mac_from_hid(hid: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.0 == hid).map(|e| e.2).filter(|&s| s != NONE)
}

/// Swap Ctrl and Cmd/Win, for driving a Mac from a PC keyboard (Ctrl+C -> Cmd+C).
pub fn swap_ctrl_gui(hid: u16) -> u16 {
    match hid {
        HID_LCTRL => HID_LGUI,
        HID_LGUI => HID_LCTRL,
        HID_RCTRL => HID_RGUI,
        HID_RGUI => HID_RCTRL,
        h => h,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_unambiguous() {
        for (i, a) in TABLE.iter().enumerate() {
            for b in &TABLE[i + 1..] {
                assert_ne!(a.0, b.0, "duplicate HID {:#x}", a.0);
                assert_ne!(a.1, b.1, "duplicate win scan {:#x}", a.1);
                assert_ne!(a.2, b.2, "duplicate mac code {:#x}", a.2);
            }
        }
    }

    #[test]
    fn win_mac_roundtrip() {
        // 'A' on Windows -> HID -> macOS kVK_ANSI_A
        let hid = hid_from_win(0x1E).unwrap();
        assert_eq!(mac_from_hid(hid), Some(0x00));
        assert_eq!(hid_from_mac(0x37), Some(HID_LGUI));
        assert_eq!(win_from_hid(HID_LGUI), Some(0xE05B));
        assert_eq!(swap_ctrl_gui(HID_LCTRL), HID_LGUI);
    }
}
